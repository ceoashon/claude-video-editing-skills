# Browse the SFX pack and render a cue list to a stereo sfx.wav (same role as the synthesized sfx.wav from music.py).
#
#   py sfx.py list [category]              categories, or the sounds in one (with durations)
#   py sfx.py catalog                      markdown list of every sound (redirect into CATALOG.md)
#   py sfx.py find <word> [word ...]       sounds whose name contains every word
#   py sfx.py render cues.json sfx.wav [--add base.wav]
#                                          place sounds on a timeline; --add layers them on top of an existing
#                                          wav (e.g. the sfx.wav music.py wrote) instead of starting from silence
#
# cues.json: {"length": 93.4, "cues": [{"t": 12.3, "sound": "Whoosh_Swish_03", "gain_db": -12, "pan": -0.3, "align": "start"}]}
#   t        seconds on the OUTPUT timeline (the same clock as g/words.js and plan.json)
#   sound    file name without .wav (or a category-relative path if two names ever collide)
#   gain_db  default per category (see DEFAULT_DB), so a bare cue already sits under the voice
#   pan      -1 (left) .. 1 (right), default 0
#   align    start | peak | end. Which part of the sound lands on t.
#            default: peak for impacts/money/clicks/dings, end for risers, start for everything else
#   length   optional; defaults to the last sound's end + 1 s. Set it to the video length so mix.py lines up.
import json, os, sys, wave
import numpy as np

SR = 48000
HERE = os.path.dirname(os.path.abspath(__file__))
SOUNDS = os.path.join(HERE, '..', 'sounds')

# Gain applied when a cue gives none. Pack is peak-normalised to -1 dB, so these keep effects well under the voice.
DEFAULT_DB = {'01': -14, '02': -10, '03': -16, '04': -16, '05': -14, '06': -14, '07': -16, '08': -14, '09': -12, '10': -16}
DEFAULT_ALIGN = {'01': 'start', '02': 'peak', '03': 'end', '04': 'peak', '05': 'peak', '06': 'peak',
                 '07': 'start', '08': 'peak', '09': 'start', '10': 'start'}


def library():
    """{name: (category_dir, path)}; also keyed 'category_dir/name' so duplicates stay addressable."""
    lib = {}
    for cat in sorted(os.listdir(SOUNDS)):
        p = os.path.join(SOUNDS, cat)
        if not os.path.isdir(p): continue
        for f in sorted(os.listdir(p)):
            if f.lower().endswith('.wav'):
                name = f[:-4]
                lib[f'{cat}/{name}'] = (cat, os.path.join(p, f))
                lib.setdefault(name, (cat, os.path.join(p, f)))
    return lib


def read(path):
    with wave.open(path, 'rb') as w:
        ch, sw, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if sw == 2: x = np.frombuffer(raw, '<i2').astype(np.float64) / 32768
    elif sw == 3:
        b = np.frombuffer(raw, np.uint8).reshape(-1, 3).astype(np.int32)
        x = ((b[:, 0] | (b[:, 1] << 8) | (b[:, 2] << 16)) << 8 >> 8).astype(np.float64) / 8388608
    else: raise SystemExit(f'{path}: unsupported sample width {sw}')
    x = x.reshape(-1, ch)
    if ch == 1: x = np.repeat(x, 2, 1)
    elif ch > 2: x = x[:, :2]
    if sr != SR:   # pack is 48 kHz; resample defensively if a file you add is not
        t = np.arange(int(len(x) * SR / sr)) * sr / SR
        x = np.stack([np.interp(t, np.arange(len(x)), x[:, c]) for c in range(2)], 1)
    return x


def write(path, x):
    x = np.clip(x, -1, 1)
    with wave.open(path, 'wb') as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((x * 32767).astype('<i2').tobytes())


def dur(path):
    with wave.open(path, 'rb') as w: return w.getnframes() / w.getframerate()


def cmd_list(args):
    lib = library(); cats = sorted({c for c, _ in lib.values()})
    if not args:
        for c in cats:
            n = sum(1 for k in lib if k.startswith(c + '/'))
            print(f'{c}  ({n})')
        return
    cat = [c for c in cats if c.startswith(args[0]) or args[0] in c]
    if not cat: raise SystemExit(f'no category matches {args[0]!r}; run `list` for the names')
    for k, (c, p) in lib.items():
        if c == cat[0] and '/' in k: print(f'{k.split("/")[1]:<32} {dur(p):5.2f}s')


def cmd_find(args):
    if not args: raise SystemExit('usage: find <word> [word ...]')
    words = [a.lower() for a in args]
    for k, (c, p) in library().items():
        if '/' in k and all(w in k.lower() for w in words): print(f'{k:<58} {dur(p):5.2f}s')


def cmd_catalog(args):
    lib = library()
    print('# Sound catalog\n\nEvery file in `sounds/`, grouped by category, with length in seconds. '
          'Generated by `py scripts/sfx.py catalog`; run `py scripts/sfx.py list <category>` for the live view.\n')
    for c in sorted({c for c, _ in lib.values()}):
        items = [(k.split('/')[1], dur(p)) for k, (cc, p) in lib.items() if cc == c and '/' in k]
        print(f'## {c} ({len(items)})\n')
        print(', '.join(f'`{n}` {d:.1f}' for n, d in items)); print()


def cmd_render(args):
    base = None
    if '--add' in args:
        i = args.index('--add'); base = args[i + 1] if i + 1 < len(args) else None
        if not base: raise SystemExit('--add needs a wav path')
        args = args[:i] + args[i + 2:]
    if len(args) != 2: raise SystemExit('usage: render cues.json out.wav [--add base.wav]')
    spec = json.load(open(args[0])); lib = library(); cues = spec['cues']
    placed, end = [], 0.0
    for i, c in enumerate(cues):
        key = c['sound'].replace('.wav', '')
        if key not in lib: raise SystemExit(f'cue {i}: unknown sound {key!r} (try `find`)')
        cat, path = lib[key]; num = cat[:2]
        x = read(path) * 10 ** (c.get('gain_db', DEFAULT_DB[num]) / 20)
        pan = float(c.get('pan', 0))
        if pan: x = x * np.array([np.cos((pan + 1) * np.pi / 4), np.sin((pan + 1) * np.pi / 4)]) * np.sqrt(2)
        align = c.get('align', DEFAULT_ALIGN[num]); n = len(x)
        a = np.abs(x).max(1)
        audible = np.nonzero(a > a.max() * 0.03)[0]     # files carry silent tails; 'end' means the last audible sample
        off = {'start': 0, 'end': int(audible[-1]) + 1, 'peak': int(a.argmax())}[align]
        s = int(round(c['t'] * SR)) - off
        if s < 0: x, s = x[-s:], 0     # a riser/peak that would start before 0:00 is trimmed, not shifted
        placed.append((s, x)); end = max(end, (s + len(x)) / SR)
    under = read(base) if base else None
    total = int(round(spec.get('length', (len(under) / SR) if base else end + 1.0) * SR))
    out = np.zeros((total, 2))
    if base: out[:min(total, len(under))] = under[:total]
    for s, x in placed:
        e = min(total, s + len(x))
        if e > s: out[s:e] += x[:e - s]
    pk = np.abs(out).max()
    if pk > 1: print(f'warning: sum peaks at {20 * np.log10(pk):+.1f} dBFS and will clip; lower some gain_db values')
    write(args[1], out)
    print(f'{len(cues)} cues -> {args[1]} ({total / SR:.1f}s)')


if __name__ == '__main__':
    cmds = {'list': cmd_list, 'find': cmd_find, 'catalog': cmd_catalog, 'render': cmd_render}
    if len(sys.argv) < 2 or sys.argv[1] not in cmds:
        sys.exit('usage: sfx.py list [category] | find <word...> | catalog | render cues.json out.wav [--add base.wav]')
    cmds[sys.argv[1]](sys.argv[2:])
